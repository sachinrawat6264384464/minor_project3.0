from typing import List, Dict, Any
from sqlalchemy.orm import Session
from app.models.project import Project
from app.models.paper import Paper
from app.models.gap import ResearchGapAnalysis, CandidateGap
from app.models.report import Report

class ReportService:
    def generate_report(
        self,
        db: Session,
        project_id: str,
        title: str,
        report_type: str = "LITERATURE_REVIEW"
    ) -> Report:
        project = db.query(Project).filter(Project.id == project_id).first()
        papers = db.query(Paper).filter(Paper.project_id == project_id).all()
        gaps = db.query(ResearchGapAnalysis).filter(ResearchGapAnalysis.project_id == project_id).all()

        md_content = self._build_markdown_report(project, papers, gaps, report_type)

        report = Report(
            project_id=project_id,
            title=title,
            report_type=report_type,
            content_markdown=md_content,
            metadata_json={"paper_count": len(papers), "gap_count": len(gaps)}
        )
        db.add(report)
        db.commit()
        db.refresh(report)
        return report

    def _build_markdown_report(
        self,
        project: Project,
        papers: List[Paper],
        gaps: List[ResearchGapAnalysis],
        report_type: str
    ) -> str:
        lines = [
            f"# {project.title} — Academic Literature & Research Gap Report",
            f"**Research Topic:** {project.research_topic}",
            f"**Primary Question:** {project.primary_question or 'N/A'}",
            f"**Generated Date:** 2026-10-10",
            "\n---\n",
            "## 1. Executive Summary",
            f"This systematic report synthesizes findings across {len(papers)} indexed academic papers "
            f"and analyzes candidate research gaps within the domain of '{project.research_topic}'.",
            "\n## 2. Reviewed Literature Collection\n"
        ]

        if papers:
            for idx, p in enumerate(papers, 1):
                authors_str = ", ".join(p.authors) if p.authors else "Unknown Authors"
                lines.append(f"### 2.{idx} {p.title}")
                lines.append(f"- **Authors:** {authors_str}")
                lines.append(f"- **Year / Venue:** {p.year or 'N/A'} | {p.venue or 'Academic Conference'}")
                lines.append(f"- **DOI:** {p.doi or 'N/A'}")
                lines.append(f"- **Abstract Summary:** {p.abstract or 'No abstract available.'}\n")
        else:
            lines.append("*No papers currently indexed in this research workspace.*")

        lines.append("\n## 3. Evidence-Backed Candidate Research Gaps\n")
        
        has_gaps = False
        for g_analysis in gaps:
            for gap in g_analysis.candidate_gaps:
                has_gaps = True
                lines.append(f"### Candidate Gap: {gap.title}")
                lines.append(f"- **Category:** `{gap.category}`")
                lines.append(f"- **Confidence Score:** `{gap.confidence_score * 100:.0f}%` ({gap.evidence_strength} Strength)")
                lines.append(f"- **Detailed Analysis:** {gap.description}")
                lines.append(f"- **Proposed Research Question:** *{gap.potential_question}*")
                lines.append(f"- **Suggested Experiment:** {gap.suggested_experiment}\n")

        if not has_gaps:
            lines.append("*Run Research Gap Analysis in your workspace to populate candidate gaps.*")

        lines.append("\n## 4. Methodological Limitations & Future Scope")
        lines.append("1. **Literature Coverage Limitations**: Gaps are evidence-supported candidate hypotheses based on ingested documents.")
        lines.append("2. **Counter-Evidence Verification**: Continuous monitoring of newer publications is recommended prior to final thesis/paper submission.")
        
        lines.append("\n---\n*Report generated by AI Research Paper & Research Gap Finder Platform*")
        return "\n".join(lines)

report_service = ReportService()
